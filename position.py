"""
Script for processing and analyzing MRI projection data acquired using the Position Method.

The script reads acquisition data from an HDF5 file generated by the CIERMag DMRS system and retrieves the corresponding acquisition and
execution protocols.

The acquired 1D signals (X, Y, Z) are processed using Fourier Transformation (FFT), with the option of applying zero-filling to
increase the number of points in the frequency domain.

The script supports acquisitions with either one or three spatial planes. It saves the acquired signals, FFT projections, and frequency
axis as NumPy files (.npy), and generates plots of the acquired signals and corresponding 1D projections using Matplotlib.

@author: Julia Marcolan
"""

import sys
import os
import numpy as np
import scipy as sc
import matplotlib.pyplot as plt
import reconstruction_functions as mri_recon

from pymr import config
from pymr.core.data import DataManager
from pymr.core.protocol import ProtocolManager
from pymr.gui.mw_processing import WidgetManager
from pymr.gui.mw_processing import InteractiveWidget
from ciermag_spec.functions import logger


# --- Read filename from the user ---
print("\nEnter the name of the file (with or without the .h5 extension):")

data_path = input("Dataset: ").strip()

# Remove quotation marks if present
data_path = data_path.strip('"').strip("'")

# Add the extension automatically if omitted
if not data_path.lower().endswith(".h5"):
    data_path += ".h5"

print("\nDataset to be loaded:")
print(f"  - {data_path}")


# --- Initialize managers ---
prot_mng = ProtocolManager()
data_mng = DataManager()
widget_mng = WidgetManager()

logger.info(f"Paths: {data_path}")
logger.info(f"Current CWD: {os.getcwd()}")

prot_mng.open_protocols(data_path=data_path)
dataset = data_mng.read_data(data_path)

logger.info(f"Original dataset shape: {dataset.shape}")


# reorganize data in the desired dimensions
type_indexer = 'type'
type_order_list = ['echo', 'readout']

data, labels, types = data_mng.get_data_from_indexer(type_indexer, type_order_list)

logger.info(f"Labels and types: {labels}, {types}")
logger.info(f"New data shape: {data.shape}")


# --- Reading parameters from the execution protocol --- 
num_planes = prot_mng.get_parameter("C_Numplanes")
logger.info(f"Num planes: {num_planes}")

rx_1SFC = prot_mng.get_parameter("Rx1SFC", "system")

DwellTime = 1.0 / (2.0 * rx_1SFC/1000)  # kHz


# --- Zero filling option ---
zero_filling = input("\nDo you want to apply zero filling? (y/n): ").strip().lower()

if zero_filling == 'y':

    zero_fill_size = int(input("Enter the desired final data size: "))

    if num_planes == 1:
        original_size = data.size

    elif num_planes == 3:
        original_size = max(len(data[0, :]), len(data[1, :]), len(data[2, :]))

    logger.info(f"Zero filling enabled. Final data size: {zero_fill_size}")

else:

    zero_filling = 'n'
    logger.info("Zero filling disabled.")


if num_planes in [1, 3]:


    # --- Single plane --- 
    if num_planes == 1:

        plane = prot_mng.get_parameter("desired_plane")

        # --- Apply zero filling if selected ---
        if zero_filling == 'y':
            data = mri_recon.zero_fill_1D(data, zero_fill_size)

        fft_echo = np.fft.fft(data)
        fft_echo = np.fft.fftshift(fft_echo)
        fft_module = np.abs(fft_echo)

        freq = np.fft.fftfreq(len(data), DwellTime)
        freq = np.fft.fftshift(freq)

        np.save('projection', fft_module)
        np.save('freq', freq)
        np.save('data', data)

        # --- Plot acquired signal and FFT projection --- 
        normalized_fft = fft_module / fft_module.max()

        fig, (ax_raw, ax_fft) = plt.subplots(1, 2, figsize=(15, 5))

        # Acquired signal
        ax_raw.plot(np.abs(data.flatten()), color='#003c64ff', linewidth=2)

        ax_raw.set_title(f'Acquired Signal - {plane} Axis')
        ax_raw.set_xlabel('Sample')
        ax_raw.set_ylabel('Magnitude')
        ax_raw.grid(True)

        # FFT projection
        ax_fft.plot(freq, normalized_fft.flatten(), color='#003c64ff', linewidth=2)

        ax_fft.set_title(f'1D Projection - {plane} Axis')
        ax_fft.set_xlabel('Frequency (kHz)')
        ax_fft.set_ylabel('Normalized Signal Intensity')
        ax_fft.grid(True)

        plt.tight_layout()
        #plt.savefig("fft_projection.png", dpi=300)
        plt.show()


    # Three planes (X, Y, Z)
    elif num_planes == 3:

        # Reorganizing the data
        data_plane_x = np.copy(data[0, :])
        data_plane_y = np.copy(data[1, :])
        data_plane_z = np.copy(data[2, :])

        # --- Apply zero filling if selected ---
        if zero_filling == 'y':

            data_plane_x = mri_recon.zero_fill_1D(data_plane_x, zero_fill_size)
            data_plane_y = mri_recon.zero_fill_1D(data_plane_y, zero_fill_size)
            data_plane_z = mri_recon.zero_fill_1D(data_plane_z, zero_fill_size)

        freq = np.fft.fftfreq(len(data_plane_x), DwellTime)
        freq = np.fft.fftshift(freq)

        # --- X --- 
        fft_echo_x = np.fft.fft(data_plane_x)
        fft_echo_x = np.fft.fftshift(fft_echo_x)
        fft_module_x = np.abs(fft_echo_x)

        # --- Y --- 
        fft_echo_y = np.fft.fft(data_plane_y)
        fft_echo_y = np.fft.fftshift(fft_echo_y)
        fft_module_y = np.abs(fft_echo_y)

        # --- Z --- 
        fft_echo_z = np.fft.fft(data_plane_z)
        fft_echo_z = np.fft.fftshift(fft_echo_z)
        fft_module_z = np.abs(fft_echo_z)


        # --- Save data --- 
        np.save('data_plane_x', data_plane_x)
        np.save('data_plane_y', data_plane_y)
        np.save('data_plane_z', data_plane_z)

        np.save('projection_x', fft_module_x)
        np.save('projection_y', fft_module_y)
        np.save('projection_z', fft_module_z)

        np.save('freq', freq)


        # --- Plot acquired signals and FFT projections --- 
        
        raw_planes = [data_plane_x, data_plane_y, data_plane_z]

        fft_planes = [fft_module_x, fft_module_y, fft_module_z]

        axis_names = ['x', 'y', 'z']

        fig, axs = plt.subplots(3, 2, figsize=(15, 10))

        for row, (raw_plane, fft_plane, axis_name) in enumerate( zip(raw_planes, fft_planes, axis_names)):

            # Acquired signal
            axs[row, 0].plot(np.abs(raw_plane), color='#003c64ff', linewidth=2)

            axs[row, 0].set_title(f'Acquired Signal - {axis_name} Axis')
            axs[row, 0].set_xlabel('Sample')
            axs[row, 0].set_ylabel('Magnitude')
            axs[row, 0].grid(True)

            # FFT projection
            normalized_fft = fft_plane / fft_plane.max()

            axs[row, 1].plot(freq, normalized_fft, color='#003c64ff', linewidth=2)

            axs[row, 1].set_title(f'1D Projection - {axis_name} Axis')
            axs[row, 1].set_xlabel('Frequency (kHz)')
            axs[row, 1].set_ylabel('Normalized Signal Intensity')
            axs[row, 1].grid(True)

        plt.tight_layout()
        #plt.savefig("fft_projection_xyz.png", dpi=300)
        plt.show()


else:

    logger.warning("It is only possible to choose 1 or 3 planes.")
